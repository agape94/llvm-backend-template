#ifndef LLVM_LIB_TARGET_SIMPLE_SIMPLESUBTARGET_H
#define LLVM_LIB_TARGET_SIMPLE_SIMPLESUBTARGET_H

#include "SimpleFrameLowering.h"
#include "SimpleISelLowering.h"
#include "SimpleInstrInfo.h"
#include "SimpleSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "SimpleGenSubtargetInfo.inc"

namespace llvm {

class SimpleSubtarget : public SimpleGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  SimpleSubtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOpt::Level OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  SimpleSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const SimpleInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const SimpleRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const SimpleTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const SimpleSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  SimpleFrameLowering FrameLowering;
  SimpleInstrInfo InstrInfo;
  SimpleTargetLowering TLInfo;
  SimpleSelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_SIMPLE_SIMPLESUBTARGET_H
