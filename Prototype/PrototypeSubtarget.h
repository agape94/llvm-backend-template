#ifndef LLVM_LIB_TARGET_PROTOTYPE_PROTOTYPESUBTARGET_H
#define LLVM_LIB_TARGET_PROTOTYPE_PROTOTYPESUBTARGET_H

#include "PrototypeFrameLowering.h"
#include "PrototypeISelLowering.h"
#include "PrototypeInstrInfo.h"
#include "PrototypeSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "PrototypeGenSubtargetInfo.inc"

namespace llvm {

class PrototypeSubtarget : public PrototypeGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  PrototypeSubtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOpt::Level OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  PrototypeSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const PrototypeInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const PrototypeRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const PrototypeTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const PrototypeSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  PrototypeFrameLowering FrameLowering;
  PrototypeInstrInfo InstrInfo;
  PrototypeTargetLowering TLInfo;
  PrototypeSelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_PROTOTYPE_PROTOTYPESUBTARGET_H
