#ifndef LLVM_LIB_TARGET_SKELETON_SKELETONSUBTARGET_H
#define LLVM_LIB_TARGET_SKELETON_SKELETONSUBTARGET_H

#include "SkeletonFrameLowering.h"
#include "SkeletonISelLowering.h"
#include "SkeletonInstrInfo.h"
#include "SkeletonSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "SkeletonGenSubtargetInfo.inc"

namespace llvm {

class SkeletonSubtarget : public SkeletonGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  SkeletonSubtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOpt::Level OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  SkeletonSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const SkeletonInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const SkeletonRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const SkeletonTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const SkeletonSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  SkeletonFrameLowering FrameLowering;
  SkeletonInstrInfo InstrInfo;
  SkeletonTargetLowering TLInfo;
  SkeletonSelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_SKELETON_SKELETONSUBTARGET_H
